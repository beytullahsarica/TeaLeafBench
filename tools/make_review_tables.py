def occlusion_table():
    o, bg = load('review_occlusion_extended.json'), load('review_bg_extended.json')
    dss = ('TeaLeafBD', 'TeaSickness')
    L = ['\\begin{tabular}{lcc}', '\\toprule',
         ' & teaLeafBD & Tea Sickness \\\\',
         ' & ($n=' + str(next(iter(o['TeaLeafBD'].values()))['trained_mean_fill_grid8']['n']) + '$) & ($n=' +
         str(next(iter(o['TeaSickness'].values()))['trained_mean_fill_grid8']['n']) + '$) \\\\', '\\midrule']

    def val(d, cond, key='index'):
        return {model_of(k): v[cond][key] for k, v in o[d].items() if v.get(cond) and v[cond].get(key) is not None
                and np.isfinite(v[cond][key])}

    def cell(cond):
        return ' & '.join(rng(val(d, cond).values()) for d in dss)
    L.append('Index, trained model, $8\\times8$, dataset-mean fill & ' + cell('trained_mean_fill_grid8') + ' \\\\')
    L.append('\\quad grey fill & ' + cell('trained_grey_fill_grid8') + ' \\\\')
    L.append('\\quad $4\\times4$ grid & ' + cell('trained_mean_fill_grid4') + ' \\\\')
    L.append('\\quad $16\\times16$ grid & ' + cell('trained_mean_fill_grid16') + ' \\\\')
    L.append(f"Index, random weights ({len(val('TeaSickness', 'random_weights_mean_fill_grid8'))} models) & "
             + cell('random_weights_mean_fill_grid8') + ' \\\\')
    L.append('\\midrule')

    def rho(d, other):
        a, b = val(d, 'trained_mean_fill_grid8'), other
        ms = [m for m in ORDER if m in a and m in b]
        return spearmanr([a[m] for m in ms], [b[m] for m in ms])[0]

    for cond, label in (('trained_grey_fill_grid8', 'grey fill'), ('trained_mean_fill_grid4', '$4\\times4$ grid'),
                        ('trained_mean_fill_grid16', '$16\\times16$ grid')):
        L.append(f'Rank correlation over models with {label} & ' + ' & '.join(f'{rho(d, val(d, cond)):+.2f}' for d in dss) + ' \\\\')

    def seed0(d, fn):
        return {model_of(k): fn(v) for k, v in bg[d]['runs'].items() if k.endswith('_s0')}
    L.append('Rank correlation with background-only accuracy & ' + ' & '.join(
        f"{rho(d, seed0(d, lambda r: r['background_only']['accuracy'])):+.2f}" for d in dss) + ' \\\\')
    L.append('Rank correlation with the loss on grey & ' + ' & '.join(
        f"{rho(d, seed0(d, lambda r: r['original']['accuracy'] - r['leaf_only']['accuracy'])):+.2f}" for d in dss) + ' \\\\')
    L.append('\\midrule')
