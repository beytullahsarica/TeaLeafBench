def load(name):
    with open(os.path.join(AN, name)) as f:
        return json.load(f)


def write(name, lines):
    with open(os.path.join(OUT, name), 'w') as f:
        f.write(re.sub(r'(?<=[ (])-(?=\d)', r'$-$', '\n'.join([HEAD] + lines)) + '\n')
    print(f'{name}: {len(lines)} lines', flush=True)


def model_of(run):
    return run.split('_224_')[0].split('_', 1)[1]


def per_model(runs, fn):
    """mean over seeds of fn(run result) for every model"""
    d = defaultdict(list)
    for k, v in runs.items():
        x = fn(v)
        if x is not None and np.isfinite(x):
            d[model_of(k)].append(float(x))
    return {m: float(np.mean(v)) for m, v in d.items()}


def rng(vals, scale=100.0, digits=1):
    v = np.asarray(list(vals), dtype=float) * scale
    return f'{v.mean():.{digits}f} ({v.min():.{digits}f}' + (' to ' if v.min() < 0 else '--') + f'{v.max():.{digits}f})'


def test_f1(model, tag, ds='teadisease', key='macro_f1'):
    out = []
    for f in sorted(glob.glob(os.path.join(ROOT, 'results', f'{ds}_{model}_224_{tag}_s[0-9]', 'test_results.json'))):
        with open(f) as h:
            out.append(json.load(h)[key])
    return out


def seeds_cell(v):
    """mean (seed 0, 1, 2) in per cent"""
    v = np.asarray(v, dtype=float) * 100
    return f'{v.mean():.1f} (' + ', '.join(f'{x:.0f}' for x in v) + ')' if len(v) else '--'


def summary_table():
    """main_summary.tex: macro-F1 of all models on the three datasets and their cost (all metrics: main_<dataset>.tex)"""
    dss = ('tealeafbd', 'teasickness', 'teadisease')
    vals = {d: {m: np.asarray(test_f1(m, 'base', d), dtype=float) * 100 for m in ORDER} for d in dss}
    best = {d: max(v.mean() for v in vals[d].values()) for d in dss}
    L = ['\\begin{tabular}{lccccc}', '\\toprule',
         ' & \\multicolumn{3}{c}{Macro-F1} & \\multicolumn{2}{c}{Cost} \\\\', '\\cmidrule(lr){2-4}\\cmidrule(lr){5-6}',
         'Model & teaLeafBD & Tea Sickness & TeaDisease & Params (M) & GFLOPs \\\\', '\\midrule']
    for m in ORDER:
        cells = []
        for d in dss:
            v = vals[d][m]
            t = f'{v.mean():.1f}'
            cells.append((f'\\textbf{{{t}}}' if abs(v.mean() - best[d]) < 1e-9 else t) + f'{{\\scriptsize$\\pm${v.std(ddof=1):.1f}}}')
        with open(os.path.join(ROOT, 'results', f'tealeafbd_{m}_224_base_s0', 'complexity.json')) as f:
            c = json.load(f)
        L.append(f"{NAME[m]} & " + ' & '.join(cells) + f" & {c['params_m']:.1f} & {c['gflops']:.1f} \\\\")
    L += ['\\bottomrule', '\\end{tabular}']
    write('main_summary.tex', L)


